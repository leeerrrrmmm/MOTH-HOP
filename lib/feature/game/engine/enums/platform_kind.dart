enum PlatformKind {
  normal, // обычная — 1 прыжок, остаётся
  fragile, // ломается сразу после 1 прыжка — исчезает
  breakable, // 3 состояния: целая → пригнутая → сломанная (сквозь неё падаем)
  jumpPad, // пружина — подкидывает вверх на N плит
  teleport, // засасывает и выплёвывает выше
  moving, // движется влево-вправо
  spike, // колючая — мгновенная смерть
}
